#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";

const START = "<!-- krn-agent-workflow:start -->";
const END = "<!-- krn-agent-workflow:end -->";
const TRACKERS = new Set(["none", "beads", "github", "gitlab", "local"]);
const DOMAINS = new Set(["single", "multi"]);
const DELIVERY = new Set(["local", "strict"]);

function fail(message) {
  process.stderr.write(`repository-workflow: ${message}\n`);
  process.exit(64);
}

function parseArgs(argv) {
  const [command = "inspect", ...rest] = argv;
  const options = {};
  for (let index = 0; index < rest.length; index += 1) {
    const flag = rest[index];
    if (!flag.startsWith("--")) fail(`unexpected argument: ${flag}`);
    const name = flag.slice(2);
    const value = rest[index + 1];
    if (!value || value.startsWith("--")) fail(`missing value for --${name}`);
    options[name] = value;
    index += 1;
  }
  return { command, options };
}

function git(root, args) {
  try {
    return execFileSync("git", ["-C", root, ...args], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    }).trim();
  } catch {
    return "";
  }
}

function redactRemote(remote) {
  if (!remote) return remote;
  try {
    const parsed = new URL(remote);
    if (parsed.username || parsed.password) {
      parsed.username = "";
      parsed.password = "";
      return parsed.toString();
    }
  } catch {
    // SCP-style Git remotes and opaque providers have no URL userinfo to redact.
  }
  return remote;
}

function regularOrSymlink(path) {
  const stat = lstatSync(path, { throwIfNoEntry: false });
  if (!stat) return false;
  return stat.isFile() || stat.isSymbolicLink();
}

function instructionState(root) {
  const agents = join(root, "AGENTS.md");
  const hasAgents = regularOrSymlink(agents);
  return { agents, hasAgents };
}

function chooseInstruction(root, requested) {
  const state = instructionState(root);
  if (requested && requested !== "AGENTS.md") fail("--instruction must be AGENTS.md");
  if (state.hasAgents) return state.agents;
  fail("no root AGENTS.md; create the repository instruction owner first");
}

function isInside(root, path) {
  const pathFromRoot = relative(root, path);
  return pathFromRoot === "" || (!pathFromRoot.startsWith(`..${sep}`) && pathFromRoot !== "..");
}

function assertInstructionSafe(root, path) {
  const target = realpathSync(path);
  if (!isInside(realpathSync(root), target)) {
    fail(`instruction owner resolves outside repository: ${relative(root, path)}`);
  }
}

function assertManagedFileSafe(root, path, expected) {
  const rootReal = realpathSync(root);
  const pathFromRoot = relative(root, path);
  if (!pathFromRoot || pathFromRoot.startsWith(`..${sep}`) || pathFromRoot === "..") {
    fail(`unsafe managed file path: ${path}`);
  }
  let current = root;
  for (const part of pathFromRoot.split(sep).slice(0, -1)) {
    current = join(current, part);
    const currentStat = lstatSync(current, { throwIfNoEntry: false });
    if (!currentStat) break;
    if (currentStat.isSymbolicLink()) {
      fail(`managed file path crosses symlink: ${relative(root, current)}`);
    }
    if (!currentStat.isDirectory()) {
      fail(`managed file path component is not a directory: ${relative(root, current)}`);
    }
    if (!isInside(rootReal, realpathSync(current))) {
      fail(`managed file path resolves outside repository: ${relative(root, current)}`);
    }
  }
  const destinationStat = lstatSync(path, { throwIfNoEntry: false });
  if (!destinationStat) return;
  if (destinationStat.isSymbolicLink() || !destinationStat.isFile()) {
    fail(`managed file destination is not a regular file: ${pathFromRoot}`);
  }
  const existingContents = readFileSync(path, "utf8");
  const owned = existingContents.startsWith("# generated by setup-repository-workflow\n");
  if (existingContents !== expected && !owned) {
    fail(`refusing unowned managed file collision: ${pathFromRoot}`);
  }
}

function inspect(root) {
  const state = instructionState(root);
  const remote = git(root, ["remote", "get-url", "origin"]);
  const provider = remote.includes("github") ? "github" : remote.includes("gitlab") ? "gitlab" : "unknown";
  const packageJson = join(root, "package.json");
  let workspaces = false;
  if (existsSync(packageJson)) {
    try {
      workspaces = Boolean(JSON.parse(readFileSync(packageJson, "utf8")).workspaces);
    } catch {
      workspaces = false;
    }
  }
  const monorepo = existsSync(join(root, "pnpm-workspace.yaml")) || workspaces;
  const instruction = state.hasAgents ? "AGENTS.md" : "missing";
  return {
    root,
    head: git(root, ["rev-parse", "HEAD"]),
    status: git(root, ["status", "--short", "--branch"]),
    remote: redactRemote(remote),
    provider,
    instruction,
    trackerSignals: {
      beads: existsSync(join(root, ".beads")),
      localMarkdown: existsSync(join(root, ".scratch")),
    },
    domainSuggestion: monorepo ? "multi" : "single",
    managedRuns: existsSync(join(root, ".krn", "runs")),
    strictDeliverySignals: {
      githubWorkflow: existsSync(join(root, ".github", "workflows")),
      codeowners: existsSync(join(root, ".github", "CODEOWNERS")),
    },
  };
}

function trackerSummary(tracker) {
  if (tracker === "none") {
    return "No durable tracker is configured. The accepted request or native Goal owns current continuation; reconcile it with Delivery Loop's capsule, repository state, and host readback. Shared queue, claims, and durable frontier state are absent. Do not emulate tracker operations or create task/status files. `$wayfinder` and any workflow requiring shared tracker state must stop until closer repository instructions configure a real tracker and its exact operations.";
  }
  if (tracker === "beads") {
    return "Beads owns durable task state and supplies Wayfinder's deterministic tracker operations. Create a map with `bd create --title <map-title> --type epic --labels wayfinder:map --body-file <map.md> --silent`, create children with `bd create --title <ticket-title> --parent <map> --labels <ticket-type> --no-inherit-labels --body-file <ticket.md> --silent`, add edges with `bd dep add <blocked> <blocker>`, claim with `bd update <id> --claim`, write a resolution or other body state with `bd update <id> --body-file <ticket.md>`, query the frontier with `bd list --parent <map> --ready --json`, close with `bd close <id>`, and read back with `bd show <id> --json`. Persist tracker-authority state, map-integrator identity, writer generation, `TRANSFER_PENDING` successor identity and return channel, `ACTIVE` with activation `PENDING`, and matching `VERIFIED` activation in the map body. Copy only the active map-integrator identity, writer generation, and exact worker-result return channel into every open child body. Use the same update operation for each transfer phase, then read back the parent and every open child before the next phase or frontier work. Resolve separate tracker-write authority before any mutation. Keep at most one implementation item in progress.";
  }
  const requiredAdapter = "exact map create/update, child create/update, dependency-edge write, atomic claim, resolution write, frontier query, close/readback, persisted map-integrator identity and tracker-authority state, writer generation, `TRANSFER_PENDING` successor identity and return channel, `ACTIVE` with activation `PENDING`, matching `VERIFIED` activation, parent and every open-child readback after each transfer phase, and one exact runtime worker-result return channel";
  if (tracker === "github") {
    return `GitHub issues own durable task state through \`gh issue create|edit|view|list|close\` inside this clone. This thin setup is not a complete Wayfinder adapter: \`$wayfinder\` must stop unless closer repository instructions define ${requiredAdapter}. Resolve separate tracker-write authority before any mutation. Keep at most one implementation item active.`;
  }
  if (tracker === "gitlab") {
    return `GitLab issues own durable task state through \`glab issue create|update|view|list|close\` inside this clone. This thin setup is not a complete Wayfinder adapter: \`$wayfinder\` must stop unless closer repository instructions define ${requiredAdapter}. Resolve separate tracker-write authority before any mutation. Keep at most one implementation item active.`;
  }
  return `Local Markdown under \`.scratch/<map>/\` owns durable task state through \`map.md\` plus numbered child files. This thin setup is not a complete Wayfinder adapter: \`$wayfinder\` must stop unless closer repository instructions define ${requiredAdapter}. Resolve separate tracker-write authority before any mutation. Keep at most one implementation item active.`;
}

function domainSummary(domain) {
  const indexing = domain === "multi"
    ? "Use root `CONTEXT.md` as the compact index to any independently owned subtree context"
    : "Use root `CONTEXT.md` for compact shared vocabulary";
  return `${indexing} when present. Create or change context, \`docs/adr/\`, or \`docs/research/\` only when active vocabulary, an earned consequential decision, or a named research consumer requires it.`;
}

function deliverySummary(delivery) {
  if (delivery === "strict") {
    return "Use one outcome branch and pull request, preferring squash merges so the maintained subject is the PR title; run focused proof before publication, honor required host checks, and keep commit, push, merge, and deployment as separate authority.";
  }
  return "Work on one accepted outcome at a time and run focused proof before local completion. Branch, PR, CI, merge, and deployment follow explicit repository or host policy.";
}

function managedBlock(tracker, domain, delivery) {
  return `${START}
## Agent workflow

- **Tracker:** ${trackerSummary(tracker)}
- **Domain knowledge:** ${domainSummary(domain)}
- **Delivery:** ${deliverySummary(delivery)}
- **Transient runs:** Keep resumable workflow state under the ignored \`.krn/runs/<workflow>/<run-id>/\`. Delete it when its sole in-goal consumer finishes the accepted outcome or its owning Goal closes; cross-Goal continuation transfers condensed truth into the successor's own run first. For a superseded or abandoned delivery run, transfer alone is not consumer completion: retain the original until its Goal's non-active state is read back. When the installed \`krn-codex\` CLI is available, verify a file-backed outcome capsule with \`krn-codex state check\` from the repository root before resuming or completing.
- **Repository memory:** Cross-run lessons live in \`docs/research/workflow-lessons.md\`. When the installed \`krn-codex\` CLI is available, run \`krn-codex lessons check --root .\`, re-run recorded proofs with \`krn-codex lessons verify --root .\`, and bump a stale proof anchor after its case passes with \`krn-codex lessons reanchor --root .\`.

Installed global skills own implementation, diagnosis, review, and reusable engineering procedure. Do not copy or rename them in this repository.
${END}`;
}

function replaceManagedBlock(current, block) {
  const start = current.indexOf(START);
  const end = current.indexOf(END);
  if ((start === -1) !== (end === -1)) fail("instruction file has an incomplete managed block");
  if (start !== -1) {
    if (end < start) fail("instruction file has reversed managed block markers");
    if (current.indexOf(START, start + START.length) !== -1 || current.indexOf(END, end + END.length) !== -1) {
      fail("instruction file has duplicate managed blocks");
    }
    return `${current.slice(0, start)}${block}${current.slice(end + END.length)}`;
  }
  return `${current.trimEnd()}\n\n${block}\n`;
}

function writeOwned(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents.endsWith("\n") ? contents : `${contents}\n`);
}

function thinAgentsTemplate(root) {
  const name = root.split(sep).filter(Boolean).pop() ?? "this repository";
  return `# ${name}

<One line: what this repository is.>

## Layout

<Where the code lives.>

## Commands

<Build, test, run — or "none yet".>

## Standing rules

- <This repository's hard constraints.>
- Methodology — production loop, proof budget, review, lifecycle — is owned by
  the installed global skills and the global \`AGENTS.md\`, auto-composed by the
  harness. It is not repeated here.
`;
}

const LESSONS_PATH = join("docs", "research", "workflow-lessons.md");

function lessonsTemplate() {
  return [
    "# Workflow lessons",
    "",
    "Repository-scoped cross-run lessons. Each row carries the evidence that earned",
    "it and the gate that enforces it. Bounded at 24 active rows; `krn-codex lessons",
    "check --root .` verifies the schema and `krn-codex lessons verify --root .` re-runs recorded proofs.",
    "",
    "| Lesson | Evidence | Enforced by | Occurrences | Falsifier | Trigger | Status |",
    "|---|---|---|---|---|---|---|",
    "",
  ].join("\n");
}

function safeLstat(path) {
  try {
    return lstatSync(path, { throwIfNoEntry: false });
  } catch {
    return undefined;
  }
}

// Memory is optional, so seed the page only when absent and never overwrite a
// repository's own lessons.
function bootstrapLessonsIfAbsent(root) {
  const target = join(root, LESSONS_PATH);
  if (safeLstat(target)) return [];
  const contents = lessonsTemplate();
  assertManagedFileSafe(root, target, contents);
  mkdirSync(dirname(target), { recursive: true });
  try {
    writeFileSync(target, contents, { flag: "wx" });
  } catch (error) {
    if (error.code === "EEXIST") return [];
    throw error;
  }
  return [LESSONS_PATH];
}

// The skill owns the repo brief: when no instruction owner exists, seed a thin
// AGENTS.md (specifics only), so a tracker's init (e.g. bd) never fills the
// void with its own always-loaded reference bloat.
function bootstrapInstructionIfAbsent(root) {
  const state = instructionState(root);
  if (state.hasAgents) return [];
  if (lstatSync(state.agents, { throwIfNoEntry: false })) {
    fail(`instruction bootstrap destination is occupied: ${relative(root, state.agents)}`);
  }
  assertManagedFileSafe(root, state.agents, "");
  try {
    writeFileSync(state.agents, thinAgentsTemplate(root), { flag: "wx" });
  } catch (error) {
    if (error.code === "EEXIST") {
      fail(`instruction bootstrap destination is occupied: ${relative(root, state.agents)}`);
    }
    throw error;
  }
  return ["AGENTS.md"];
}

const { command, options } = parseArgs(process.argv.slice(2));
const root = resolve(options.root ?? process.cwd());
if (!existsSync(root)) fail(`root does not exist: ${root}`);

if (command === "inspect") {
  process.stdout.write(`${JSON.stringify(inspect(root), null, 2)}\n`);
  process.exit(0);
}
if (command !== "apply") fail("command must be inspect or apply");

const tracker = options.tracker;
const domain = options.domain;
const delivery = options.delivery;
if (!TRACKERS.has(tracker)) fail("--tracker must be none, beads, github, gitlab, or local");
if (!DOMAINS.has(domain)) fail("--domain must be single or multi");
if (!DELIVERY.has(delivery)) fail("--delivery must be local or strict");

const managedFiles = new Map([
  [join(root, ".krn", "runs", ".gitignore"), "# generated by setup-repository-workflow\n*\n!.gitignore\n"],
]);
for (const [path, contents] of managedFiles) assertManagedFileSafe(root, path, contents);

const lessonsTarget = join(root, LESSONS_PATH);
if (!safeLstat(lessonsTarget)) assertManagedFileSafe(root, lessonsTarget, lessonsTemplate());
const bootstrapped = bootstrapInstructionIfAbsent(root);
const lessonsBootstrapped = bootstrapLessonsIfAbsent(root);
const instructionPath = chooseInstruction(root, options.instruction);
assertInstructionSafe(root, instructionPath);
const current = readFileSync(instructionPath, "utf8");
const next = replaceManagedBlock(current, managedBlock(tracker, domain, delivery));

writeOwned(instructionPath, next);
for (const [path, contents] of managedFiles) writeOwned(path, contents);

const written = [...new Set([
  ...bootstrapped,
  ...lessonsBootstrapped,
  relative(root, instructionPath),
  ...[...managedFiles.keys()].map((path) => relative(root, path)),
])];

process.stdout.write(`${JSON.stringify({
  root,
  instruction: relative(root, instructionPath),
  tracker,
  domain,
  delivery,
  written,
}, null, 2)}\n`);
