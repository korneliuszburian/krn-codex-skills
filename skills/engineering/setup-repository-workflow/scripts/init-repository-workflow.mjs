#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";

const START = "<!-- krn-agent-workflow:start -->";
const END = "<!-- krn-agent-workflow:end -->";
const OWNED = "<!-- generated by setup-repository-workflow -->";
const TRACKERS = new Set(["beads", "github", "gitlab", "local"]);
const DOMAINS = new Set(["single", "multi"]);
const DELIVERY = new Set(["local", "strict"]);

function fail(message) {
  process.stderr.write(`repository-workflow: ${message}\n`);
  process.exit(64);
}

function parseArgs(argv) {
  const [command = "inspect", ...rest] = argv;
  const options = {};
  for (let index = 0; index < rest.length; index += 1) {
    const flag = rest[index];
    if (!flag.startsWith("--")) fail(`unexpected argument: ${flag}`);
    const name = flag.slice(2);
    const value = rest[index + 1];
    if (!value || value.startsWith("--")) fail(`missing value for --${name}`);
    options[name] = value;
    index += 1;
  }
  return { command, options };
}

function git(root, args) {
  try {
    return execFileSync("git", ["-C", root, ...args], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    }).trim();
  } catch {
    return "";
  }
}

function regularOrSymlink(path) {
  if (!existsSync(path)) return false;
  const stat = lstatSync(path);
  return stat.isFile() || stat.isSymbolicLink();
}

function instructionState(root) {
  const agents = join(root, "AGENTS.md");
  const claude = join(root, "CLAUDE.md");
  const hasAgents = regularOrSymlink(agents);
  const hasClaude = regularOrSymlink(claude);
  const sameSemanticFile = hasAgents && hasClaude && realpathSync(agents) === realpathSync(claude);
  return { agents, claude, hasAgents, hasClaude, sameSemanticFile };
}

function chooseInstruction(root, requested) {
  const state = instructionState(root);
  if (requested) {
    if (!new Set(["AGENTS.md", "CLAUDE.md"]).has(requested)) {
      fail("--instruction must be AGENTS.md or CLAUDE.md");
    }
    const selected = join(root, requested);
    if (!regularOrSymlink(selected)) fail(`${requested} does not exist`);
    return selected;
  }
  if (state.hasAgents && state.hasClaude && !state.sameSemanticFile) {
    fail("AGENTS.md and CLAUDE.md are independent; select --instruction explicitly");
  }
  if (state.hasAgents) return state.agents;
  if (state.hasClaude) return state.claude;
  fail("no root AGENTS.md or CLAUDE.md; create the repository instruction owner first");
}

function isInside(root, path) {
  const pathFromRoot = relative(root, path);
  return pathFromRoot === "" || (!pathFromRoot.startsWith(`..${sep}`) && pathFromRoot !== "..");
}

function assertInstructionSafe(root, path) {
  const target = realpathSync(path);
  if (!isInside(realpathSync(root), target)) {
    fail(`instruction owner resolves outside repository: ${relative(root, path)}`);
  }
}

function assertAdapterSafe(root, path, expected) {
  const rootReal = realpathSync(root);
  const pathFromRoot = relative(root, path);
  if (!pathFromRoot || pathFromRoot.startsWith(`..${sep}`) || pathFromRoot === "..") {
    fail(`unsafe adapter path: ${path}`);
  }
  let current = root;
  for (const part of pathFromRoot.split(sep).slice(0, -1)) {
    current = join(current, part);
    if (!existsSync(current)) break;
    if (lstatSync(current).isSymbolicLink()) {
      fail(`adapter path crosses symlink: ${relative(root, current)}`);
    }
    if (!isInside(rootReal, realpathSync(current))) {
      fail(`adapter path resolves outside repository: ${relative(root, current)}`);
    }
  }
  if (!existsSync(path)) return;
  if (lstatSync(path).isSymbolicLink() || !lstatSync(path).isFile()) {
    fail(`adapter destination is not an owned regular file: ${pathFromRoot}`);
  }
  const existingContents = readFileSync(path, "utf8");
  let ownedJson = false;
  if (path.endsWith(".json")) {
    try {
      const parsed = JSON.parse(existingContents);
      ownedJson = parsed?._generated_by === "setup-repository-workflow" &&
        parsed?.schema_version === 1;
    } catch {
      ownedJson = false;
    }
  }
  const owned = existingContents.startsWith(`${OWNED}\n`) ||
    existingContents.startsWith("# generated by setup-repository-workflow\n") ||
    ownedJson;
  if (existingContents !== expected && !owned) {
    fail(`refusing unowned adapter collision: ${pathFromRoot}`);
  }
}

function inspect(root) {
  const state = instructionState(root);
  const remote = git(root, ["remote", "get-url", "origin"]);
  const provider = remote.includes("github") ? "github" : remote.includes("gitlab") ? "gitlab" : "unknown";
  const packageJson = join(root, "package.json");
  let workspaces = false;
  if (existsSync(packageJson)) {
    try {
      workspaces = Boolean(JSON.parse(readFileSync(packageJson, "utf8")).workspaces);
    } catch {
      workspaces = false;
    }
  }
  const monorepo = existsSync(join(root, "pnpm-workspace.yaml")) || workspaces;
  const instruction = state.sameSemanticFile
    ? "AGENTS.md (shared with CLAUDE.md)"
    : state.hasAgents && state.hasClaude
      ? "conflict"
      : state.hasAgents
        ? "AGENTS.md"
        : state.hasClaude
          ? "CLAUDE.md"
          : "missing";
  return {
    root,
    head: git(root, ["rev-parse", "HEAD"]),
    status: git(root, ["status", "--short", "--branch"]),
    remote,
    provider,
    instruction,
    trackerSignals: {
      beads: existsSync(join(root, ".beads")),
      localMarkdown: existsSync(join(root, ".scratch")),
    },
    domainSuggestion: monorepo ? "multi" : "single",
    existingAdapters: existsSync(join(root, "docs", "agents")),
    strictDeliverySignals: {
      githubWorkflow: existsSync(join(root, ".github", "workflows")),
      codeowners: existsSync(join(root, ".github", "CODEOWNERS")),
    },
  };
}

function trackerDoc(tracker) {
  if (tracker === "beads") {
    return `${OWNED}
# Issue tracker: Beads

Beads owns durable task state, dependencies, blockers, claims, follow-ups, and handoffs for this repository.

## Conventions

- Read ready work with \`bd ready\` and inspect one item with \`bd show <id>\`.
- Keep exactly one implementation bead \`in_progress\` at most; a blocked bead remains the sole active implementation item.
- Claim before implementation; do not create a second active item to bypass a blocker.
- Close only after the acceptance result and required proof exist. Record an external blocker with its owner and requested decision.
- Beads is the queue, not reusable knowledge, implementation history, or a replacement for domain documentation.
`;
  }
  if (tracker === "github") {
    return `${OWNED}
# Issue tracker: GitHub

Issues for this repository live in GitHub. Use \`gh\` inside this clone so the remote selects the repository.

## Conventions

- Read with \`gh issue view <number> --comments\`; list the ready frontier with the repository's labels and dependency policy.
- Claim by assigning the issue before implementation. Keep at most one active implementation item.
- Use native sub-issues and dependencies when available; otherwise keep one explicit \`Blocked by: #<n>\` line.
- Resolve with a concise result and proof, then close. Pull requests are delivery artifacts, not a second issue queue.
`;
  }
  if (tracker === "gitlab") {
    return `${OWNED}
# Issue tracker: GitLab

Issues for this repository live in GitLab. Use \`glab\` inside this clone so the remote selects the project.

## Conventions

- Read with \`glab issue view <number> --comments\`; list the ready frontier with the project's labels and blocking links.
- Claim by assigning the issue before implementation. Keep at most one active implementation item.
- Use native blocking links when available; otherwise keep one explicit \`Blocked by: #<n>\` line.
- Post the result and proof before closing. Merge requests are delivery artifacts, not a second issue queue.
`;
  }
  return `${OWNED}
# Issue tracker: Local Markdown

Issues and specifications live below \`.scratch/\`.

## Conventions

- Use one feature directory and one file per ticket: \`.scratch/<feature>/issues/<NN>-<slug>.md\`.
- Record status, blockers, acceptance, and proof in that ticket. First open, unblocked, unclaimed number is the frontier.
- Claim before implementation and keep at most one active implementation ticket.
- Resolve the ticket after proof; do not create a combined backlog document or duplicate current status elsewhere.
`;
}

function domainDoc(domain) {
  const layout = domain === "multi"
    ? "Read root `CONTEXT-MAP.md`, then only the context files and ADRs relevant to the task."
    : "Read root `CONTEXT.md` and only ADRs relevant to the task.";
  return `${OWNED}
# Domain docs

${layout}

If a file does not exist, proceed silently. Create or change domain documentation only when an active terminology conflict or durable architecture decision earns it.

Use the repository's defined vocabulary in issues, code, tests, and review. Surface an ADR conflict explicitly instead of silently overriding it. Domain docs own shared language and durable decisions; they do not own current status, task queues, or implementation detail.
`;
}

function deliveryDoc(delivery) {
  if (delivery === "strict") {
    return `${OWNED}
# Delivery profile: strict PR

- One accepted outcome uses one branch and one pull request.
- Use cohesive Conventional Commits; do not force the PR number into every inner commit.
- Run focused local proof before publication. Required CI must observe the changed risk on the fixed PR revision.
- Review the fixed diff on Standards and Spec axes. Automated review is advisory unless the host ruleset requires its approval, resolved threads, or named status.
- Merge only through the repository host policy. Prefer linear history and squash when the host ruleset selects them; the durable squash commit carries \`(#PR)\`.
- Commit, push, PR, merge, and deployment remain separate authority boundaries.
`;
  }
  return `${OWNED}
# Delivery profile: local

- Work on one accepted outcome at a time and keep commits cohesive and reviewable.
- Run focused proof and fixed-point Standards/Spec review before declaring local completion.
- Branch, pull request, required CI, merge, and deployment follow explicit repository or host policy; do not invent them locally.
- Commit, push, PR, merge, and deployment remain separate authority boundaries.
`;
}

function artifactsDoc() {
  return `${OWNED}
# Agent artifacts

Agent workflows use two repository-local tiers:

- \`docs/agents/runs/<workflow>/<run-id>/\` — disposable working material such as prompts, manifests, logs, shards, and intermediate reviewer output. The directory is ignored by Git so a fixed-point review does not change the reviewed diff.
- \`docs/agents/reports/<workflow>/<slug>.md\` — an intentionally retained final synthesis, decision, or owner-facing report with a named consumer.

The workflow that creates a run owns its contents and cleanup. Remove a working run when its task or review is accepted, superseded, or abandoned. Do not promote raw corpora, credentials, private customer data, or generated logs into tracked documentation.

Chat output is sufficient unless a later session, owner, CI job, or decision explicitly consumes a persisted report. A retained report links its source revision or fixed point and states what it does not prove.

Every workflow resolves these roles through \`docs/agents/artifact-paths.json\`; individual skills do not hardcode a different root.
`;
}

function artifactPaths() {
  return `${JSON.stringify({
    _generated_by: "setup-repository-workflow",
    schema_version: 1,
    working_runs: "docs/agents/runs",
    retained_reports: "docs/agents/reports",
    durable_research: "docs/research",
    architecture_decisions: "docs/adr",
  }, null, 2)}\n`;
}

function reviewDoc() {
  return `${OWNED}
# Review context

Every fixed-point reviewer receives the complete decision context, not an unbounded repository dump:

1. requested result and authoritative acceptance/spec;
2. fixed base/head revision, commit list, diff, and complete changed-path ledger;
3. closest applicable instructions plus only durable domain/ADR material relevant to the changed boundary;
4. exact focused proof commands, results, known gaps, and generated paths;
5. authority and publication state, explicit non-goals, and what current evidence does not prove;
6. separate Standards and Spec questions.

Put a transient context manifest below the configured \`working_runs\` root. Persist a final review only when a named consumer needs it, below \`retained_reports/code-review/\`. Review remains read-only; a parent workflow performs any later persistence or repair.
`;
}

function managedBlock(tracker, domain, delivery) {
  const trackerLabel = tracker === "beads" ? "Beads" : tracker === "local" ? "local Markdown" : tracker[0].toUpperCase() + tracker.slice(1);
  const domainLabel = domain === "multi" ? "multi-context" : "single-context";
  const deliveryLabel = delivery === "strict" ? "strict PR" : "local";
  return `${START}
## Agent workflow

### Issue tracker

${trackerLabel} owns the durable queue and claim state. See \`docs/agents/issue-tracker.md\`.

### Domain docs

Use the ${domainLabel} domain layout. See \`docs/agents/domain.md\`.

### Delivery

Use the ${deliveryLabel} delivery profile. See \`docs/agents/delivery.md\`.

### Agent artifacts

Use the repository-local working and retained report paths in \`docs/agents/artifacts.md\`.

### Review context

Give reviewers the complete bounded decision packet defined in \`docs/agents/review.md\`.

Installed global skills own implementation, diagnosis, review, and reusable engineering procedure. Do not copy or rename them in this repository.
${END}`;
}

function replaceManagedBlock(current, block) {
  const start = current.indexOf(START);
  const end = current.indexOf(END);
  if ((start === -1) !== (end === -1)) fail("instruction file has an incomplete managed block");
  if (start !== -1) {
    if (end < start) fail("instruction file has reversed managed block markers");
    if (current.indexOf(START, start + START.length) !== -1 || current.indexOf(END, end + END.length) !== -1) {
      fail("instruction file has duplicate managed blocks");
    }
    return `${current.slice(0, start)}${block}${current.slice(end + END.length)}`;
  }
  return `${current.trimEnd()}\n\n${block}\n`;
}

function writeOwned(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents.endsWith("\n") ? contents : `${contents}\n`);
}

function thinAgentsTemplate(root) {
  const name = root.split(sep).filter(Boolean).pop() ?? "this repository";
  return `# ${name}

<One line: what this repository is.>

## Layout

<Where the code lives.>

## Commands

<Build, test, run — or "none yet".>

## Standing rules

- <This repository's hard constraints.>
- Methodology — production loop, proof budget, review, lifecycle — is owned by
  the installed global skills and the global \`AGENTS.md\`, auto-composed by the
  harness. It is not repeated here.
`;
}

// The skill owns the repo brief: when no instruction owner exists, seed a thin
// AGENTS.md (specifics only) and symlink CLAUDE.md to it, so a tracker's init
// (e.g. bd) never fills the void with its own always-loaded reference bloat.
function bootstrapInstructionIfAbsent(root) {
  const state = instructionState(root);
  if (state.hasAgents || state.hasClaude) return;
  writeFileSync(state.agents, thinAgentsTemplate(root));
  try {
    symlinkSync("AGENTS.md", state.claude);
  } catch {
    // CLAUDE.md is optional; ignore if it cannot be created.
  }
}

const { command, options } = parseArgs(process.argv.slice(2));
const root = resolve(options.root ?? process.cwd());
if (!existsSync(root)) fail(`root does not exist: ${root}`);

if (command === "inspect") {
  process.stdout.write(`${JSON.stringify(inspect(root), null, 2)}\n`);
  process.exit(0);
}
if (command !== "apply") fail("command must be inspect or apply");

const tracker = options.tracker;
const domain = options.domain;
const delivery = options.delivery;
if (!TRACKERS.has(tracker)) fail("--tracker must be beads, github, gitlab, or local");
if (!DOMAINS.has(domain)) fail("--domain must be single or multi");
if (!DELIVERY.has(delivery)) fail("--delivery must be local or strict");

bootstrapInstructionIfAbsent(root);
const instructionPath = chooseInstruction(root, options.instruction);
assertInstructionSafe(root, instructionPath);
const current = readFileSync(instructionPath, "utf8");
const next = replaceManagedBlock(current, managedBlock(tracker, domain, delivery));
const adapters = new Map([
  [join(root, "docs", "agents", "issue-tracker.md"), trackerDoc(tracker)],
  [join(root, "docs", "agents", "domain.md"), domainDoc(domain)],
  [join(root, "docs", "agents", "delivery.md"), deliveryDoc(delivery)],
  [join(root, "docs", "agents", "artifacts.md"), artifactsDoc()],
  [join(root, "docs", "agents", "artifact-paths.json"), artifactPaths()],
  [join(root, "docs", "agents", "review.md"), reviewDoc()],
  [join(root, "docs", "agents", "runs", ".gitignore"), "# generated by setup-repository-workflow\n*\n!.gitignore\n"],
]);
for (const [path, contents] of adapters) assertAdapterSafe(root, path, contents);

writeOwned(instructionPath, next);
for (const [path, contents] of adapters) writeOwned(path, contents);

process.stdout.write(`${JSON.stringify({
  root,
  instruction: relative(root, instructionPath),
  tracker,
  domain,
  delivery,
  written: [relative(root, instructionPath), "docs/agents/issue-tracker.md", "docs/agents/domain.md", "docs/agents/delivery.md", "docs/agents/artifacts.md", "docs/agents/artifact-paths.json", "docs/agents/review.md", "docs/agents/runs/.gitignore"],
}, null, 2)}\n`);
